-- ---- sp_save_product / sp_delete_product -----------------------------------
CREATE OR REPLACE PROCEDURE sp_save_product(
  p_name         IN VARCHAR2, p_sku IN VARCHAR2, p_category_id IN NUMBER,
  p_unit_price   IN NUMBER,   p_reorder_level IN NUMBER,
  p_tax_override IN NUMBER,   p_user_id IN NUMBER)
AS
BEGIN
  check_role('admin,inventory_clerk');
  INSERT INTO products (name, sku, category_id, unit_price,
                        tax_rate_override, reorder_level, created_by)
    VALUES (p_name, p_sku, p_category_id, p_unit_price,
            p_tax_override, p_reorder_level, p_user_id);
  COMMIT;
END sp_save_product;
/

CREATE OR REPLACE PROCEDURE sp_delete_product(p_product_id IN NUMBER) AS
  v_used NUMBER;
BEGIN
  check_role('admin');
  SELECT COUNT(*) INTO v_used FROM (
    SELECT 1 FROM purchase_items WHERE product_id = p_product_id
    UNION ALL
    SELECT 1 FROM sale_items     WHERE product_id = p_product_id
  );
  IF v_used > 0 THEN
    RAISE_APPLICATION_ERROR(-20002, '400: product has purchase or sale records');
  END IF;
  DELETE FROM products WHERE product_id = p_product_id;
  COMMIT;
END sp_delete_product;
/

