-- ---- sp_save_user / sp_delete_user / sp_set_user_role : admin only ---------
CREATE OR REPLACE PROCEDURE sp_save_user(
  p_username IN VARCHAR2, p_password IN VARCHAR2,
  p_full_name IN VARCHAR2, p_role_name IN VARCHAR2)
AS
BEGIN
  check_role('admin');
  INSERT INTO users (username, password_hash, full_name, role_id)
    VALUES (p_username, p_password, p_full_name,
            (SELECT role_id FROM roles WHERE role_name = p_role_name));
  COMMIT;
END sp_save_user;
/

CREATE OR REPLACE PROCEDURE sp_set_user_role(
  p_user_id IN NUMBER, p_role_name IN VARCHAR2) AS
BEGIN
  check_role('admin');
  UPDATE users
     SET role_id = (SELECT role_id FROM roles WHERE role_name = p_role_name)
   WHERE user_id = p_user_id;
  COMMIT;
END sp_set_user_role;
/

CREATE OR REPLACE PROCEDURE sp_delete_user(p_user_id IN NUMBER) AS
  v_used NUMBER;
BEGIN
  check_role('admin');
  SELECT COUNT(*) INTO v_used FROM (
    SELECT 1 FROM sales      WHERE user_id = p_user_id
    UNION ALL
    SELECT 1 FROM purchases  WHERE user_id = p_user_id
  );
  IF v_used > 0 THEN
    RAISE_APPLICATION_ERROR(-20002, '400: user has recorded sales or purchases');
  END IF;
  DELETE FROM users WHERE user_id = p_user_id;
  COMMIT;
END sp_delete_user;
