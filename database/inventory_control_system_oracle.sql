-- ===========================================================================
--  PART 2  -  package + role check  (used by triggers + procedures below)
-- ===========================================================================
-- The Node server sets the role package variable on each request.  Both the
-- triggers on inserts and the procedures raise ORA-20001 when the role is
-- not allowed.

CREATE OR REPLACE PACKAGE app_ctx_pkg AS
  FUNCTION  get_role RETURN VARCHAR2;
  PROCEDURE set_role(p_role VARCHAR2);
END app_ctx_pkg;
/
CREATE OR REPLACE PACKAGE BODY app_ctx_pkg AS
  g_role VARCHAR2(50);
  FUNCTION  get_role RETURN VARCHAR2 IS BEGIN RETURN g_role; END get_role;
  PROCEDURE set_role(p_role VARCHAR2) IS BEGIN g_role := p_role; END set_role;
END app_ctx_pkg;
/

-- Helper: raise 403 if the current request's role is not on the list.
CREATE OR REPLACE PROCEDURE check_role(p_allowed IN VARCHAR2) AS
  v_role VARCHAR2(50);
BEGIN
  v_role := app_ctx_pkg.get_role();
  IF v_role IS NULL THEN
    RAISE_APPLICATION_ERROR(-20001, '403: no session role set');
  END IF;
  IF INSTR(','||p_allowed||',', ','||v_role||',') = 0 THEN
    RAISE_APPLICATION_ERROR(-20001, '403: role not permitted for this operation');
  END IF;
END check_role;
/

-- ===========================================================================
--  PART 3  -  triggers that maintain stock + totals
--             and also enforce role-based access
-- ===========================================================================
-- Purchase received -> stock goes up, purchase total updated.
-- Only inventory_clerk / admin are allowed to record stock arrivals.
CREATE OR REPLACE TRIGGER trg_purchases_bi
BEFORE INSERT ON purchases
FOR EACH ROW
BEGIN
  check_role('admin,inventory_clerk');
END trg_purchases_bi;
/

CREATE OR REPLACE TRIGGER trg_purchase_item_ai
AFTER INSERT ON purchase_items
FOR EACH ROW
DECLARE
  v_current_stock NUMBER(10);
BEGIN
  -- stock goes up
  UPDATE products
     SET current_stock = current_stock + :NEW.quantity
   WHERE product_id = :NEW.product_id;
  -- purchase header total updated
  UPDATE purchases
     SET total_cost = total_cost + :NEW.quantity * :NEW.unit_cost
   WHERE purchase_id = :NEW.purchase_id;
END trg_purchase_item_ai;
/

-- Sale header: only sales_staff / admin may create a sale.
CREATE OR REPLACE TRIGGER trg_sales_bi
BEFORE INSERT ON sales
FOR EACH ROW
BEGIN
  check_role('admin,sales_staff');
END trg_sales_bi;
/

-- Sale line BEFORE INSERT: copy price + effective tax rate, compute
-- subtotal/tax/total, and refuse if the product does not exist.
CREATE OR REPLACE TRIGGER trg_sale_item_bi
BEFORE INSERT ON sale_items
FOR EACH ROW
DECLARE
  v_price NUMBER(12,2);
  v_rate  NUMBER(5,2);
  v_found NUMBER(1);
BEGIN
  SELECT p.unit_price,
         COALESCE(p.tax_rate_override, c.default_tax_rate),
         1
    INTO v_price, v_rate, v_found
    FROM products   p
    JOIN categories c ON c.category_id = p.category_id
   WHERE p.product_id = :NEW.product_id;
  :NEW.unit_price := v_price;
  :NEW.tax_rate   := v_rate;
  :NEW.subtotal   := ROUND(v_price * :NEW.quantity, 2);
  :NEW.tax_amount := ROUND(:NEW.subtotal * v_rate / 100, 2);
  :NEW.line_total := :NEW.subtotal + :NEW.tax_amount;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20002, '400: product '||:NEW.product_id||' not found');
END trg_sale_item_bi;
/

-- Sale line AFTER INSERT: stock goes down (CHECK blocks negative stock),
-- header totals updated.
CREATE OR REPLACE TRIGGER trg_sale_item_ai
AFTER INSERT ON sale_items
FOR EACH ROW
DECLARE
  v_stock NUMBER(10);
BEGIN
  SELECT current_stock INTO v_stock
    FROM products WHERE product_id = :NEW.product_id;
  IF v_stock < :NEW.quantity THEN
    RAISE_APPLICATION_ERROR(-20002,
      '400: insufficient stock for product '||:NEW.product_id);
  END IF;
  UPDATE products
     SET current_stock = current_stock - :NEW.quantity
   WHERE product_id = :NEW.product_id;
  UPDATE sales
     SET order_subtotal = order_subtotal + :NEW.subtotal,
         total_tax      = total_tax      + :NEW.tax_amount,
         grand_total    = grand_total    + :NEW.line_total
   WHERE sale_id = :NEW.sale_id;
END trg_sale_item_ai;
/

-- --- Views -------------------------------------------------------------------
CREATE OR REPLACE VIEW v_current_stock AS
SELECT p.product_id, p.name, p.sku, c.category_name, p.current_stock, p.reorder_level
  FROM products   p
  JOIN categories c ON c.category_id = p.category_id;
/

CREATE OR REPLACE VIEW v_low_stock AS
SELECT product_id, name, sku, current_stock, reorder_level
  FROM products
 WHERE current_stock <= reorder_level;
/

CREATE OR REPLACE VIEW v_tax_summary AS
SELECT TRUNC(s.sale_date) AS sale_day, c.category_name,
       SUM(si.subtotal)   AS taxable_amount,
       SUM(si.tax_amount) AS tax_collected
  FROM sale_items si
  JOIN sales      s  ON s.sale_id     = si.sale_id
  JOIN products   p  ON p.product_id  = si.product_id
  JOIN categories c  ON c.category_id = p.category_id
 GROUP BY TRUNC(s.sale_date), c.category_name;
/

