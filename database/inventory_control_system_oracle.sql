-- ---- sp_create_purchase: only inventory_clerk and admin -------------------
CREATE OR REPLACE PROCEDURE sp_create_purchase(
  p_supplier_id IN NUMBER, p_user_id IN NUMBER, p_product_id IN NUMBER,
  p_quantity    IN NUMBER, p_unit_cost IN NUMBER)
AS
  v_pid NUMBER;
BEGIN
  check_role('admin,inventory_clerk');
  IF p_quantity IS NULL OR p_quantity <= 0 THEN
    RAISE_APPLICATION_ERROR(-20002, '400: quantity must be greater than 0');
  END IF;
  INSERT INTO purchases (supplier_id, user_id)
    VALUES (p_supplier_id, p_user_id)
    RETURNING purchase_id INTO v_pid;
  INSERT INTO purchase_items (purchase_id, product_id, quantity, unit_cost)
    VALUES (v_pid, p_product_id, p_quantity, p_unit_cost);
  COMMIT;
END sp_create_purchase;
/

