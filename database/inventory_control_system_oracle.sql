--  3. Press "Run Script" (F5) -- NOT "Run Statement" (Ctrl+Enter).
--     "Run Script" treats "/" as the PL/SQL block terminator that the
--     file uses between every CREATE/REPLACE / BEGIN block.
--
--  The file is idempotent: it drops any previous copy of the schema
--  (tables, views, sequences, triggers, packages, procedures) before
--  recreating everything.  Order of drops is: views first (so view-
--  dependent tables can be dropped), then tables, then triggers,
--  then packages, then procedures.
-- =============================================================================


-- ===========================================================================
--  PART 0  -  drop everything that the script is going to (re)create
-- ===========================================================================
BEGIN
  -- views must go first because DROP TABLE refuses if a view references it
  FOR v IN (SELECT view_name FROM user_views) LOOP
    EXECUTE IMMEDIATE 'DROP VIEW '||v.view_name;
  END LOOP;
  FOR t IN (SELECT table_name FROM user_tables) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE '||t.table_name||' CASCADE CONSTRAINTS';
  END LOOP;
  FOR s IN (SELECT sequence_name FROM user_sequences) LOOP
    BEGIN EXECUTE IMMEDIATE 'DROP SEQUENCE '||s.sequence_name;
    EXCEPTION WHEN OTHERS THEN NULL;
    END;
  END LOOP;
  FOR tr IN (SELECT trigger_name FROM user_triggers) LOOP
    EXECUTE IMMEDIATE 'DROP TRIGGER '||tr.trigger_name;
  END LOOP;
  FOR pk IN (SELECT object_name FROM user_objects WHERE object_type='PACKAGE') LOOP
    EXECUTE IMMEDIATE 'DROP PACKAGE '||pk.object_name;
  END LOOP;
  FOR pr IN (SELECT object_name FROM user_objects WHERE object_type='PROCEDURE') LOOP
    EXECUTE IMMEDIATE 'DROP PROCEDURE '||pr.object_name;
  END LOOP;
END;
/

